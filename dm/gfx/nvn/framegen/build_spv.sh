#!/bin/bash
# Frame generation's compute shaders -> SPIR-V -> fg_spv.h (glslc from the Android NDK's shader-tools, or GLSLC=<path>)
set -e
O=$(cd "$(dirname "$0")" && pwd); G=${GLSLC:-glslc}
for f in fg_motion fg_interp; do $G -O --target-env=vulkan1.1 "$O/$f.comp" -o "$O/$f.spv"; done
python3 - "$O" <<'PY'
import struct, sys
o = sys.argv[1]; out = ['// generated by build_spv.sh from fg_motion.comp / fg_interp.comp: do not edit']
for name in ('fg_motion', 'fg_interp'):
    b = open(f'{o}/{name}.spv', 'rb').read(); w = struct.unpack('<%dI' % (len(b) // 4), b)
    out.append(f'static const uint32_t {name}_spv[{len(w)}] = {{')
    for i in range(0, len(w), 8): out.append('    ' + ', '.join('0x%08x' % x for x in w[i:i + 8]) + ',')
    out.append('};')
open(f'{o}/fg_spv.h', 'w', newline='\n').write('\n'.join(out) + '\n')
PY
